// Regenerates src/lib/blur-placeholders.ts. Run this after replacing any
// image listed in `images` below (or add a new path to the list).
//
//   node scripts/gen-blur-placeholders.js

const sharp = require("sharp");
const fs = require("fs");
const path = require("path");

const root = path.join(__dirname, "..");
const images = [
  "/images/ILC/family-group.jpg",
  "/images/ILC/class-smiles.jpg",
  "/images/ILC/welcome.jpg",
  "/images/ILC/peer-study.jpg",
  "/images/ILC/tutor-focus.jpg",
  "/images/ILC/tutoring-1on1.jpg",
  "/images/prog-gcse.jpg",
  "/images/prog-alevel.jpg",
  "/images/prog-ib.jpg",
  "/images/prog-tawjihi.jpg",
  "/images/ILC/study-pair.jpg",
  "/images/ILC/kids-creative.jpg",
];

async function main() {
  const entries = [];
  for (const img of images) {
    const filePath = path.join(root, "public", img);
    const buf = await sharp(filePath).resize(12).jpeg({ quality: 40 }).toBuffer();
    entries.push([img, `data:image/jpeg;base64,${buf.toString("base64")}`]);
    console.log(img, "->", buf.length, "bytes");
  }

  const out = `// Auto-generated by scripts/gen-blur-placeholders.js — do not hand-edit.
export const BLUR_PLACEHOLDERS: Record<string, string> = {
${entries.map(([k, v]) => `  "${k}": "${v}",`).join("\n")}
};
`;
  fs.writeFileSync(path.join(root, "src/lib/blur-placeholders.ts"), out);
  console.log("wrote src/lib/blur-placeholders.ts");
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
